const fs = require('fs');
const path = require('path');
const ts = require('typescript');
const packageJson = require('../../package.json');

// Commit this declaration so source-consuming workspaces do not need a Gen AI build first.
// Regenerate with `pnpm run generate:public-types` in packages/gen-ai/frontend.
// Implementation type-checking still runs separately against Gen AI's own tsconfig.
const entry = packageJson.exports['./MaaSModelsPageProvider'];
const packageRoot = path.resolve(__dirname, '../..');
const sourcePath = path.resolve(packageRoot, entry.default);
const declarationPath = path.resolve(packageRoot, entry.types);
const result = ts.transpileDeclaration(fs.readFileSync(sourcePath, 'utf8'), {
  fileName: sourcePath,
  compilerOptions: { jsx: ts.JsxEmit.React, newLine: ts.NewLineKind.LineFeed },
  reportDiagnostics: true,
});

if (result.diagnostics.length > 0) {
  throw new Error(
    ts.formatDiagnosticsWithColorAndContext(result.diagnostics, {
      getCanonicalFileName: (fileName) => fileName,
      getCurrentDirectory: () => packageRoot,
      getNewLine: () => '\n',
    }),
  );
}

// This public component currently only needs React types. Do not accidentally expose
// its implementation imports (including private ~/ aliases) through the declaration.
const { importedFiles } = ts.preProcessFile(result.outputText);
if (importedFiles.some(({ fileName }) => fileName !== 'react')) {
  throw new Error('Public component types must be self-contained and only import React.');
}

const declaration = `// Generated by pnpm run generate:public-types. Do not edit.\n${result.outputText}`;
if (process.argv.includes('--check')) {
  if (!fs.existsSync(declarationPath) || fs.readFileSync(declarationPath, 'utf8') !== declaration) {
    throw new Error(
      'Public types are stale. Run pnpm run generate:public-types and commit the result.',
    );
  }
} else {
  fs.mkdirSync(path.dirname(declarationPath), { recursive: true });
  fs.writeFileSync(declarationPath, declaration);
}
